"""Train the on-device classifiers and export them as a C header.

    python training/train.py                       # evaluate + export to training/output/
    python training/train.py --deploy              # also overwrite the firmware header

Data: data/raw/class_<label>.csv, one file per class, recorded with
tools/collect_dataset.py (columns: session,label,window_id,index,x,y,z,sample_rate_hz).
The class label is taken from the file name.

Models (both exported, firmware uses the Random Forest):
  - Random Forest, 150 trees  -> pm_rf_* arrays (flattened sklearn trees)
  - Logistic Regression with StandardScaler folded into the weights -> pm_lr_*
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

sys.path.insert(0, str(Path(__file__).resolve().parent))
from features import FEATURE_NAMES, N, window_features  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SEED = 42


def load_dataset(data_dir: Path) -> tuple[np.ndarray, np.ndarray, list[str]]:
    files = sorted(data_dir.glob("class_*.csv"))
    if not files:
        raise SystemExit(f"no class_*.csv files in {data_dir}")
    X, y, labels = [], [], []
    for path in files:
        label = re.match(r"class_(.+)\.csv", path.name)[1]
        labels.append(label)
        df = pd.read_csv(path)
        for _, w in df.groupby("window_id", sort=True):
            w = w.sort_values("index")
            if len(w) != N or not (w["index"].to_numpy() == np.arange(N)).all():
                continue
            X.append(window_features(w[["x", "y", "z"]].to_numpy()))
            y.append(len(labels) - 1)
        print(f"  {path.name}: {sum(1 for c in y if c == len(labels) - 1)} windows")
    return np.array(X), np.array(y), labels


def make_rf() -> RandomForestClassifier:
    return RandomForestClassifier(n_estimators=150, max_depth=6, min_samples_leaf=2,
                                  random_state=SEED, n_jobs=-1)


def make_lr():
    return make_pipeline(StandardScaler(), LogisticRegression(max_iter=5000, C=1.0))


# ----------------------------------------------------------------------------- export
def _c_array(ctype: str, name: str, values, fmt) -> str:
    vals = [fmt(v) for v in values]
    rows = [", ".join(vals[i:i + 8]) for i in range(0, len(vals), 8)]
    body = ",\n  ".join(rows)
    return f"static const {ctype} {name}[{len(vals)}] = {{\n  {body},\n}};\n"


def _f(v: float) -> str:
    s = f"{float(v):.9g}"
    if "e" not in s and "." not in s and "inf" not in s:
        s += ".0"
    return s + "f"


def export_header(rf: RandomForestClassifier, lr, n_classes: int, path: Path) -> None:
    scaler, logreg = lr.named_steps["standardscaler"], lr.named_steps["logisticregression"]
    # Fold standardisation: w' = w / sigma,  b' = b - sum(w * mu / sigma)
    w = logreg.coef_ / scaler.scale_
    b = logreg.intercept_ - (logreg.coef_ * scaler.mean_ / scaler.scale_).sum(axis=1)

    offsets, feat, thr, left, right, vals = [], [], [], [], [], []
    for est in rf.estimators_:
        t = est.tree_
        base = len(feat)
        offsets.append(base)
        feat += t.feature.tolist()                     # leaves are -2
        thr += t.threshold.tolist()
        left += [(c + base) if c >= 0 else -1 for c in t.children_left]
        right += [(c + base) if c >= 0 else -1 for c in t.children_right]
        v = t.value[:, 0, :]
        v = v / v.sum(axis=1, keepdims=True)           # class fractions per node
        vals += v.ravel().tolist()

    out = ["#ifndef PM_MODELS_DATA_H\n#define PM_MODELS_DATA_H\n",
           "/* Generated by training/train.py - do not edit. */\n",
           f"#define PM_FEATURES {w.shape[1]}\n#define PM_CLASSES {n_classes}\n",
           _c_array("float", "pm_lr_w", w.ravel(), _f),
           _c_array("float", "pm_lr_b", b, _f),
           f"#define PM_RF_TREES {len(offsets)}\n#define PM_RF_NODES {len(feat)}\n",
           _c_array("int", "pm_rf_offsets", offsets, str),
           _c_array("int", "pm_rf_feature", feat, str),
           _c_array("float", "pm_rf_threshold", thr, _f),
           _c_array("int", "pm_rf_left", left, str),
           _c_array("int", "pm_rf_right", right, str),
           _c_array("float", "pm_rf_values", vals, _f),
           "#endif\n"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(out))


# ----------------------------------------------------------------------------- main
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", type=Path, default=ROOT / "data" / "raw")
    ap.add_argument("--out", type=Path, default=ROOT / "training" / "output")
    ap.add_argument("--deploy", action="store_true",
                    help="also write firmware/Services/Inference/generated/pm_models_data.h")
    args = ap.parse_args()

    print("Loading windows + extracting features ...")
    X, y, labels = load_dataset(args.data)
    names = labels
    print(f"Dataset: {X.shape[0]} windows x {X.shape[1]} features, {len(labels)} classes")

    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
    report = {}
    for name, factory in (("random_forest", make_rf), ("logistic_regression", make_lr)):
        pred = cross_val_predict(factory(), X, y, cv=cv)
        acc = accuracy_score(y, pred)
        report[name] = {"cv5_accuracy": round(acc, 4),
                        "confusion_matrix": confusion_matrix(y, pred).tolist()}
        print(f"\n== {name}: 5-fold CV accuracy {acc:.3f}")
        print(classification_report(y, pred, target_names=names, digits=3))
        print(confusion_matrix(y, pred))

    rf, lr = make_rf().fit(X, y), make_lr().fit(X, y)
    top = np.argsort(rf.feature_importances_)[::-1][:10]
    report["top_features"] = [[FEATURE_NAMES[i], round(float(rf.feature_importances_[i]), 4)] for i in top]
    report["rf_nodes"] = int(sum(e.tree_.node_count for e in rf.estimators_))
    report["labels"] = names

    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "metrics.json").write_text(json.dumps(report, indent=2))
    header = args.out / "pm_models_data.h"
    export_header(rf, lr, len(labels), header)
    print(f"\nRF nodes: {report['rf_nodes']}  ->  {header}")
    if args.deploy:
        dst = ROOT / "firmware" / "Services" / "Inference" / "generated" / "pm_models_data.h"
        dst.write_text(header.read_text())
        print(f"deployed -> {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
